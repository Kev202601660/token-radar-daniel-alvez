// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// Implied value follows only from the snapshot's own figures. Where the starter used a flat 0.25x
// multiple on TVL, this model derives the multiple from the snapshot itself: for each category it
// reads the market-cap-to-TVL ratio of the protocols that already trade, takes the median, and
// shrinks it toward the whole-market median by how many comparables the category has. A pre-token
// DEX is then priced like the DEXs that already launched, a pre-token lending protocol like the
// lenders, and so on. No protocol name is ever special-cased: the same function scores every row.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them and the sandbox may change them. */
export interface ModelConstants {
  /** Growth is clamped to this range and each point moves value by growth_weight per cent. */
  growth_floor: number;
  growth_cap: number;
  growth_weight: number;
  /** Maturity: 0.6x for a brand-new protocol up to 1.0x once it has run maturity_days without a token. */
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  /** Sector blend: a category with n comparables is n/(n+shrink) of its own median. */
  shrink: number;
  /** Sector multiples are clamped to this range so one outlier cannot dominate. */
  sector_floor: number;
  sector_cap: number;
}

export const MODEL: ModelConstants = {
  growth_floor: -60,
  growth_cap: 120,
  growth_weight: 0.5,
  maturity_floor: 0.6,
  maturity_range: 0.4,
  maturity_days: 1095,
  unknown_age_days: 365,
  shrink: 3,
  sector_floor: 0.005,
  sector_cap: 5,
};

/** The model's version label: the dashboard names it and the rules quote it. */
export const MODEL_VERSION = 'comparable-market-1';

